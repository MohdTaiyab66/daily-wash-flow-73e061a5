#!/usr/bin/env node
/**
 * Capacitor plugin-registry hard gate (run right after `cap sync android`).
 *
 * Prints the generated plugin registry and the app's plugin map, then FAILS
 * the build if anything can still route payments through the legacy
 * com.ionicframework.capacitor.Checkout plugin.
 *
 * Fails when:
 *   - capacitor.plugins.json references capacitor-razorpay / ionicframework Checkout
 *   - any Java/Kotlin source registers Checkout.class
 *   - any JS/TS source calls registerPlugin("Checkout") or Plugins.Checkout
 *   - capacitor-razorpay is present in node_modules / manifests / gradle graph
 *   - Checkout.preload( is called from app-owned sources
 *   - UrbanWashCheckoutPlugin is not the single registered payment plugin
 */
import fs from "node:fs";
import path from "node:path";
import { PAYMENTS_ENABLED, VARIANT } from "./lib/variant.mjs";

const results = [];
const record = (name, ok, detail = "") => results.push({ name, ok, detail });

const read = (p) => {
  try {
    return fs.readFileSync(p, "utf8");
  } catch {
    return null;
  }
};

const LEGACY_TOKENS = [
  "com.ionicframework.capacitor.Checkout",
  "com/ionicframework/capacitor/Checkout",
  "capacitor-razorpay",
];

const EXPECTED_PLUGIN_CLASS = "com.urbanwash.payments.UrbanWashCheckoutPlugin";
const EXPECTED_PLUGIN_NAME = "UrbanWashCheckout";

// --- 1. Generated plugin registry -------------------------------------------
const REGISTRY = "android/app/src/main/assets/capacitor.plugins.json";
const registryRaw = read(REGISTRY);

console.log("");
console.log("============================================================");
console.log(" CAPACITOR PLUGIN REGISTRY (generated by cap sync)");
console.log("============================================================");
if (registryRaw) {
  console.log(REGISTRY);
  try {
    const list = JSON.parse(registryRaw);
    for (const entry of list) {
      console.log(`  ${String(entry.pkg ?? "?").padEnd(48)} -> ${entry.classpath ?? "?"}`);
    }
  } catch {
    console.log(registryRaw);
  }
} else {
  console.log(`  (missing: ${REGISTRY} — run cap sync android first)`);
}
console.log("");

record("registry.present", !!registryRaw, registryRaw ? REGISTRY : `${REGISTRY} not generated`);
if (registryRaw) {
  const legacy = LEGACY_TOKENS.filter((t) => registryRaw.includes(t));
  record(
    "registry.no-legacy-checkout",
    legacy.length === 0,
    legacy.length ? `registry references ${legacy.join(", ")}` : "no legacy Checkout entry",
  );
}

// --- 2. Native plugin map (app-owned registrations) --------------------------
const NATIVE_SOURCE_ROOTS = ["android/app/src/main/java", "android-native"];
const nativeFiles = [];
const walk = (dir) => {
  let entries = [];
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const e of entries) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (/\.(java|kt)$/.test(e.name)) nativeFiles.push(p);
  }
};
NATIVE_SOURCE_ROOTS.forEach(walk);

const registrations = [];
for (const file of nativeFiles) {
  const src = read(file) ?? "";
  for (const m of src.matchAll(/registerPlugin\(\s*([\w.]+)\.class\s*\)/g)) {
    registrations.push({ file, cls: m[1] });
  }
}

console.log("============================================================");
console.log(" NATIVE PLUGIN MAP (registerPlugin call sites)");
console.log("============================================================");
if (registrations.length === 0) console.log("  (none)");
for (const r of registrations) console.log(`  ${r.cls.padEnd(28)} <- ${r.file}`);
console.log(`  @CapacitorPlugin name expected by JS: ${EXPECTED_PLUGIN_NAME}`);
console.log("");

// TEMPORARY DIAGNOSTIC — remove once the partner build is confirmed green.
console.log("VERIFY VARIANT =", process.env.URBANWASH_APP);
console.log(`  resolved VARIANT=${VARIANT}  PAYMENTS_ENABLED=${PAYMENTS_ENABLED}`);

// Only registrations inside the generated Android project decide the variant
// gate. `android-native/` holds the repo-owned templates that get restored into
// the project for the Customer build; they must not be double-counted (and must
// not fail the Partner build, which simply never copies them).
// NOTE: path.join() yields backslashes on Windows, so compare on a normalised
// posix-style path — otherwise every registration is filtered out and the
// summary contradicts the plugin map printed above.
const toPosix = (p) => p.split(path.sep).join("/").replace(/\\/g, "/");
const projectRegistrations = registrations.filter((r) => toPosix(r.file).startsWith("android/"));

if (PAYMENTS_ENABLED) {
  record(
    "native.registration.single",
    projectRegistrations.length === 1 &&
      projectRegistrations[0].cls.split(".").pop() === "UrbanWashCheckoutPlugin",
    projectRegistrations.length
      ? projectRegistrations.map((r) => `${r.cls} (${r.file})`).join(", ")
      : "no registerPlugin call found in android/",
  );
  record(
    "native.template.customer-mainactivity",
    !!read("android-native/java/com/urbanwash/customer/MainActivity.java"),
    "android-native/java/com/urbanwash/customer/MainActivity.java must exist so cap add android can be re-run",
  );
} else {
  // Partner collects no payments: no payment plugin may be registered at all.
  const paymentRegs = projectRegistrations.filter((r) => /Checkout/i.test(r.cls));
  record(
    "native.registration.no-payment-plugin",
    paymentRegs.length === 0,
    paymentRegs.length ? paymentRegs.map((r) => `${r.cls} (${r.file})`).join(", ") : "no payment plugin registered (partner)",
  );
}

record(
  "native.no-legacy-registration",
  !registrations.some((r) => /(^|\.)Checkout$/.test(r.cls)),
  "registerPlugin(Checkout.class) must not exist",
);

const pluginSrc = read("android/app/src/main/java/com/urbanwash/payments/UrbanWashCheckoutPlugin.java");
if (PAYMENTS_ENABLED) {
  record(
    "native.plugin-name",
    !!pluginSrc && pluginSrc.includes(`@CapacitorPlugin(name = "${EXPECTED_PLUGIN_NAME}")`),
    pluginSrc ? `plugin declares name ${EXPECTED_PLUGIN_NAME}` : "app-module plugin source missing",
  );
  record(
    "native.plugin-fqcn",
    !!pluginSrc && pluginSrc.includes("package com.urbanwash.payments;"),
    `expected ${EXPECTED_PLUGIN_CLASS}`,
  );
} else {
  record("native.plugin-source.absent", !pluginSrc, pluginSrc ? `${EXPECTED_PLUGIN_CLASS} must not exist in the partner project` : "no payment plugin source in partner project");
}

// --- 3. JS/TS references -----------------------------------------------------
const jsFiles = [];
const walkJs = (dir) => {
  let entries = [];
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const e of entries) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walkJs(p);
    else if (/\.(ts|tsx|js|jsx|mjs)$/.test(e.name)) jsFiles.push(p);
  }
};
walkJs("src");

const jsOffenders = [];
const jsRegistrations = [];
for (const file of jsFiles) {
  const src = read(file) ?? "";
  for (const m of src.matchAll(/registerPlugin\s*<[^>]*>\s*\(\s*["'`]([^"'`]+)["'`]|registerPlugin\s*\(\s*["'`]([^"'`]+)["'`]/g)) {
    jsRegistrations.push({ file, name: m[1] ?? m[2] });
  }
  if (/Plugins\s*\.\s*Checkout\b/.test(src)) jsOffenders.push(`${file}: Plugins.Checkout`);
  if (/registerPlugin\s*(<[^>]*>)?\s*\(\s*["'`]Checkout["'`]/.test(src)) jsOffenders.push(`${file}: registerPlugin("Checkout")`);
  if (src.includes("capacitor-razorpay")) jsOffenders.push(`${file}: capacitor-razorpay reference`);
}

console.log("============================================================");
console.log(" JS PLUGIN MAP (registerPlugin bindings)");
console.log("============================================================");
if (jsRegistrations.length === 0) console.log("  (none)");
for (const r of jsRegistrations) console.log(`  ${r.name.padEnd(28)} <- ${r.file}`);
console.log("");

record("js.no-legacy-reference", jsOffenders.length === 0, jsOffenders.join("; ") || "no legacy Checkout reference in src/");
const paymentBindings = jsRegistrations.filter((r) => /checkout/i.test(r.name));
if (PAYMENTS_ENABLED) {
  record(
    "js.payment-binding.single",
    paymentBindings.length === 1 && paymentBindings[0].name === EXPECTED_PLUGIN_NAME,
    paymentBindings.map((r) => `${r.name} (${r.file})`).join(", ") || "no payment plugin binding found",
  );
} else {
  // The shared web bundle still contains the customer checkout module, but the
  // partner APK ships no native payment plugin, so nothing can invoke it.
  record(
    "js.payment-binding.at-most-one",
    paymentBindings.length <= 1,
    paymentBindings.map((r) => `${r.name} (${r.file})`).join(", ") || "no payment plugin binding found",
  );
}

// --- 4. Dependency / gradle graph -------------------------------------------
record("deps.node_modules.clean", !fs.existsSync("node_modules/capacitor-razorpay"), "node_modules/capacitor-razorpay must not exist");
for (const manifest of ["package.json", "bun.lock", "package-lock.json"]) {
  const src = read(manifest);
  if (src === null) continue;
  record(`deps.manifest.clean.${path.basename(manifest)}`, !src.includes("capacitor-razorpay"), `${manifest}`);
}
for (const gradleFile of ["android/capacitor.settings.gradle", "android/app/capacitor.build.gradle"]) {
  const src = read(gradleFile);
  if (src === null) continue;
  record(`gradle.clean.${path.basename(gradleFile)}`, !src.includes("capacitor-razorpay"), gradleFile);
}

// --- 5. preload() must never be called by app-owned code ---------------------
const preloadOffenders = [];
for (const file of nativeFiles) {
  const src = (read(file) ?? "").replace(/\/\/[^\n]*|\/\*[\s\S]*?\*\//g, "");
  if (/Checkout\s*\.\s*preload\s*\(|\.preload\s*\(/.test(src)) preloadOffenders.push(file);
}
record("native.no-preload-call", preloadOffenders.length === 0, preloadOffenders.join(", ") || "no Checkout.preload( call in app-owned native sources");

// --- Summary -----------------------------------------------------------------
const pass = results.every((r) => r.ok);
console.log("============================================================");
console.log(` PLUGIN REGISTRY VERIFICATION (variant: ${VARIANT}, payments: ${PAYMENTS_ENABLED ? "enabled" : "disabled"})`);
console.log("============================================================");
for (const r of results) console.log(`  ${r.ok ? "[PASS]" : "[FAIL]"} ${r.name}${r.detail ? "  -  " + r.detail : ""}`);
console.log("------------------------------------------------------------");
console.log(pass ? " RESULT: PASS" : " RESULT: FAIL");
console.log("============================================================");
console.log("");

process.exit(pass ? 0 : 1);
